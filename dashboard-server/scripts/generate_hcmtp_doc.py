#!/usr/bin/env python3
"""Generate docs/hcmtp-metric-calculations.md from the audit CSV.

The CSV (docs/hcmtp-metric-audit.csv) is the single source of truth for how
each HCMTP metric is defined (paper Table II), how the code currently computes
it, and what assumptions we make. This script renders that into readable
Markdown so the two never drift.

Usage:
    python dashboard-server/scripts/generate_hcmtp_doc.py
"""
from __future__ import annotations

import csv
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CSV_PATH = REPO_ROOT / "docs" / "hcmtp-metric-audit.csv"
OUT_PATH = REPO_ROOT / "docs" / "hcmtp-metric-calculations.md"

GLOBAL_ASSUMPTIONS = [
    "**Measurement window:** all telemetry rows from the TOR until the scenario auto-ends. "
    "The paper (Table II) says \"after the TOR\" but gives no duration, so we fix the window as TOR to end-of-run.",
    "**Sampling:** CARLA telemetry is sampled at ~30 Hz; brief peaks may be missed.",
    "**Steering units:** CARLA `steer` is a normalized command in [-1, +1]. We convert to degrees with "
    "`steer x 450`, assuming a 900 deg lock-to-lock steering wheel. This is an assumption, not a measurement.",
    "**Brake units:** CARLA `brake` is normalized in [0, 1]. We convert to MPa with `brake x 5`, assuming "
    "5 MPa max brake pressure. CARLA provides no true brake pressure.",
    "**Throttle units:** CARLA `throttle` in [0, 1] is converted to % with `x 100`.",
    "**Lane centre:** taken from the CARLA map waypoint centre; approximate on curved segments.",
    "**Yaw reference:** yaw angle and yaw acceleration are relative to the vehicle heading at the TOR (planned).",
    "**Standardisation:** every metric is z-scored against a per-preset human baseline before PCA weights are applied.",
]


def _cell(text: str) -> str:
    """Escape a value for use inside a Markdown table cell."""
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def main() -> None:
    rows = list(csv.DictReader(CSV_PATH.open(newline="")))

    lines: list[str] = []
    lines.append("# HCMTP Metric Calculations & Assumptions")
    lines.append("")
    lines.append(
        "> **Auto-generated** from [`hcmtp-metric-audit.csv`](./hcmtp-metric-audit.csv) by "
        "`dashboard-server/scripts/generate_hcmtp_doc.py`. Do not edit this file by hand."
    )
    lines.append("")
    lines.append(
        "This document states exactly how each of the 41 HCMTP metrics is calculated in TakeoverBench, "
        "what we assume where the paper is silent, and whether the current code matches the paper."
    )
    lines.append("")

    lines.append("## Global assumptions")
    lines.append("")
    for item in GLOBAL_ASSUMPTIONS:
        lines.append(f"- {item}")
    lines.append("")

    lines.append("## Per-metric calculation & assumptions")
    lines.append("")
    lines.append("| # | Metric | Unit | Paper definition (Table II) | How the code calculates it | Our assumption | Status |")
    lines.append("|---|--------|------|-----------------------------|----------------------------|----------------|--------|")
    for r in rows:
        lines.append(
            "| {no} | {abbr} | {unit} | {defn} | {formula} | {assumption} | {status} |".format(
                no=_cell(r["no"]),
                abbr=_cell(r["abbr"]),
                unit=_cell(r["unit"]),
                defn=_cell(r["paper_definition"]),
                formula=_cell(r["current_formula"]),
                assumption=_cell(r["assumption"]),
                status=_cell(r["status"]),
            )
        )
    lines.append("")
    lines.append("## Status legend")
    lines.append("")
    lines.append("| Status | Meaning |")
    lines.append("|---|---|")
    lines.append("| `OK` | Code matches the paper definition. |")
    lines.append("| `OK-ASSUMED` | Paper is ambiguous; code follows our documented assumption. |")
    lines.append("| `APPROX` | Uses an assumed conversion or CARLA approximation. |")
    lines.append("| `DECIDE` | Paper is ambiguous; a decision is required. |")
    lines.append("| `BUG` | Code contradicts the paper definition; fix required. |")
    lines.append("| `DEFERRED` | Not implemented. |")
    lines.append("")

    OUT_PATH.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT_PATH.relative_to(REPO_ROOT)} ({len(rows)} metrics)")


if __name__ == "__main__":
    main()
